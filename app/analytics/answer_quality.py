# ============================================================================
# LATENCY
# ============================================================================

def latency_metrics(
    df: Optional[pd.DataFrame] = None,
) -> dict:
    """Return latency statistics for the evaluation run."""

    if df is None:
        df = load_answer_quality_results()

    retrieval = _numeric_column(
        df,
        "retrieval_ms",
    )

    generation = _numeric_column(
        df,
        "generation_ms",
    )

    total = _numeric_column(
        df,
        "total_ms",
    )

    return {
        "retrieval_mean_ms": (
            float(retrieval.mean())
            if not retrieval.dropna().empty
            else None
        ),

        "generation_mean_ms": (
            float(generation.mean())
            if not generation.dropna().empty
            else None
        ),

        "total_mean_ms": (
            float(total.mean())
            if not total.dropna().empty
            else None
        ),

        "retrieval_min_ms": (
            float(retrieval.min())
            if not retrieval.dropna().empty
            else None
        ),

        "retrieval_max_ms": (
            float(retrieval.max())
            if not retrieval.dropna().empty
            else None
        ),

        "generation_min_ms": (
            float(generation.min())
            if not generation.dropna().empty
            else None
        ),

        "generation_max_ms": (
            float(generation.max())
            if not generation.dropna().empty
            else None
        ),

        "total_min_ms": (
            float(total.min())
            if not total.dropna().empty
            else None
        ),

        "total_max_ms": (
            float(total.max())
            if not total.dropna().empty
            else None
        ),
    }


# ============================================================================
# DISPLAY HELPERS
# ============================================================================

def format_percentage(
    value: Optional[float],
) -> str:
    """Format a percentage."""
    if value is None:
        return "N/A"

    return f"{value:.2f}%"


def format_score(
    value: Optional[float],
) -> str:
    """Format a 0–1 score as a percentage."""

    if value is None:
        return "N/A"

    return f"{value * 100:.2f}%"


def format_ms(
    value: Optional[float],
) -> str:
    """Format milliseconds."""

    if value is None:
        return "N/A"

    return f"{value:.2f} ms"


